// Builds the two files you paste into the Supabase SQL editor.
//   npm run db:build-sql
//   db/supabase_setup.sql        tables + demo shoes, demo customers and the demo admin   (good for a first look or a class demo)
//   db/supabase_schema_only.sql  tables only, no shoes and no accounts                     (the real shop; then add shoes in the admin page)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const read = (f) => fs.readFileSync(path.join(here, f), 'utf8').trim();

const drops = `-- Start clean: removes only Shushop's own tables.
DROP VIEW IF EXISTS product_ratings;
${['notifications', 'order_status_log', 'order_items', 'orders', 'coupons', 'stock_alerts', 'cart_items', 'favourites', 'reviews', 'variants', 'products', 'brands', 'addresses', 'sessions', 'users']
  .map((t) => `DROP TABLE IF EXISTS ${t} CASCADE;`).join('\n')}`;

const banner = (what) => `-- Shushop database setup (${what}).
-- Supabase: open "SQL Editor", paste this whole file, press Run. Safe to run again: it starts by dropping Shushop's tables.
-- Generated by "npm run db:build-sql" from db/schema.sql${what.includes('demo') ? ' and db/seed.sql' : ''}. Do not edit by hand.
`;

const bare = `${banner('tables only')}\n${drops}\n\n${read('schema.sql')}\n`;
// The real shop still needs its coupons table rows only if the owner wants them; nothing is seeded here.
const demo = `${banner('tables and demo data')}\n${drops}\n\n${read('schema.sql')}\n\n${read('seed.sql')}\n`;

fs.writeFileSync(path.join(here, 'supabase_schema_only.sql'), bare);
fs.writeFileSync(path.join(here, 'supabase_setup.sql'), demo);
console.log(`Wrote db/supabase_setup.sql (${demo.length} bytes) and db/supabase_schema_only.sql (${bare.length} bytes).`);
